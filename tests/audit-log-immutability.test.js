/**
 * Integration Test Suite: Immutable Audit Log (Trigger Enforcement)
 *
 * Implements Prompt 17 (Scope 1, audit_log trigger rejects UPDATE/DELETE, database.md §6.5 / D-15):
 * - Validates database trigger trg_audit_log_immutable
 * - Proves audit_log is strictly append-only
 * - Negative tests: UPDATE and DELETE statements raise PostgreSQL exceptions
 */
const { Client } = require('pg');

const DB_URL = process.env.DATABASE_URL || 'postgresql://postgres:b4c2de80b80e3bebc18adbde993908a9@localhost:5432/bd_commerce?schema=public';

async function runAuditLogImmutabilityTests() {
  console.log('\n--- 2. Testing Audit Log PostgreSQL Immutability (database.md §6.5) ---');
  let passed = 0;
  let failed = 0;

  function assert(condition, message) {
    if (condition) {
      console.log(`  ✓ PASS: ${message}`);
      passed++;
    } else {
      console.error(`  ✗ FAIL: ${message}`);
      failed++;
    }
  }

  const pg = new Client({ connectionString: DB_URL });
  await pg.connect();

  try {
    // 1. Verify triggers exist
    const triggerRes = await pg.query(`
      SELECT tgname FROM pg_trigger WHERE tgrelid = 'audit_log'::regclass
    `);
    const triggers = triggerRes.rows.map(r => r.tgname);
    assert(triggers.includes('trg_audit_log_immutable'), 'Trigger trg_audit_log_immutable is active on audit_log');
    assert(triggers.includes('trg_audit_log_chain'), 'Trigger trg_audit_log_chain is active on audit_log');

    // 2. Insert valid audit record
    const testId = `audit_test_${Date.now()}`;
    await pg.query(`
      INSERT INTO audit_log (id, action, entity_type, entity_id, actor_type, actor_id, created_at)
      VALUES ($1, 'test_record', 'system_test', 'entity_001', 'system', 'usr_system', now())
    `, [testId]);
    assert(true, 'Successfully inserted test audit log row (Append operation)');

    // Verify row was stored with sha256 hash generated by chain trigger
    const rowRes = await pg.query(`SELECT id, action, record_hash FROM audit_log WHERE id = $1`, [testId]);
    assert(rowRes.rows.length === 1 && Boolean(rowRes.rows[0].record_hash), 'Audit row created with cryptographic record_hash');

    // 3. Negative Test: Attempt UPDATE on audit_log (MUST FAIL)
    let updateFailed = false;
    try {
      await pg.query(`UPDATE audit_log SET action = 'tampered' WHERE id = $1`, [testId]);
    } catch (err) {
      updateFailed = err.message.includes('audit_log is append-only (attempted UPDATE)');
    }
    assert(updateFailed, 'UPDATE operation strictly rejected: "audit_log is append-only (attempted UPDATE)"');

    // 4. Negative Test: Attempt DELETE on audit_log (MUST FAIL)
    let deleteFailed = false;
    try {
      await pg.query(`DELETE FROM audit_log WHERE id = $1`, [testId]);
    } catch (err) {
      deleteFailed = err.message.includes('audit_log is append-only (attempted DELETE)');
    }
    assert(deleteFailed, 'DELETE operation strictly rejected: "audit_log is append-only (attempted DELETE)"');

    // 5. Verify row integrity after failed tampering attempts
    const verifyRes = await pg.query(`SELECT action FROM audit_log WHERE id = $1`, [testId]);
    assert(verifyRes.rows[0].action === 'test_record', 'Audit row remains completely unmutated and intact');

  } catch (err) {
    console.error('Audit log test execution error:', err);
    failed++;
  } finally {
    await pg.end();
  }

  return { passed, failed };
}

if (require.main === module) {
  runAuditLogImmutabilityTests().then(result => {
    process.exit(result.failed > 0 ? 1 : 0);
  });
}

module.exports = { runAuditLogImmutabilityTests };
